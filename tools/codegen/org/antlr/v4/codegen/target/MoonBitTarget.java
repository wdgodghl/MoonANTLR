package org.antlr.v4.codegen.target;

import java.io.IOException;
import java.io.Writer;
import java.util.*;
import org.antlr.v4.codegen.CodeGenerator;
import org.antlr.v4.runtime.atn.ATNSerializer;
import org.antlr.v4.tool.*;
import org.antlr.v4.tool.ast.*;
import org.antlr.v4.parse.ANTLRParser;
import org.stringtemplate.v4.*;

/** ANTLR 4.13.2 plugin. Emits MoonBit over the portable ATN runtime.
 * Java templates are used solely to construct ANTLR's output model; no Java
 * recognizer is emitted, translated, or needed by the generated program.
 */
public final class MoonBitTarget extends JavaTarget {
    public MoonBitTarget(CodeGenerator generator) { super(generator); }

    @Override protected STGroup loadTemplates() {
        STGroup group = new STGroupFile(JavaTarget.class.getResource(
            "/org/antlr/v4/tool/templates/codegen/Java/Java.stg"), "UTF-8", '<', '>');
        group.registerRenderer(Integer.class, new NumberRenderer());
        group.registerRenderer(String.class, new StringRenderer());
        return group;
    }
    @Override public String getRecognizerFileName(boolean header) { return gen.g.getRecognizerName() + ".mbt"; }
    @Override public String getListenerFileName(boolean header) { return gen.g.name + "Listener.mbt"; }
    @Override public String getVisitorFileName(boolean header) { return gen.g.name + "Visitor.mbt"; }
    @Override public boolean wantsBaseListener() { return false; }
    @Override public boolean wantsBaseVisitor() { return false; }

    private static String q(String text) {
        StringBuilder out = new StringBuilder("\"");
        text.codePoints().forEach(c -> {
            switch (c) {
                case '"': out.append("\\\""); break;
                case '\\': out.append("\\\\"); break;
                case '\n': out.append("\\n"); break;
                case '\r': out.append("\\r"); break;
                case '\t': out.append("\\t"); break;
                default: if (c < 32) out.append("\\u{").append(Integer.toHexString(c)).append('}');
                         else out.appendCodePoint(c);
            }
        });
        return out.append('"').toString();
    }
    // Prefix all grammar-derived methods to avoid collisions with runtime helpers
    // and MoonBit keywords. Types are prefixed by the recognizer's grammar name.
    private static String method(String name) { return "get_" + name; }
    private static String type(Grammar g, String name) {
        return g.name + Character.toUpperCase(name.charAt(0)) + name.substring(1) + "Context";
    }
    private static void block(StringBuilder out, String code) {
        if (code.startsWith("pub(all) struct ")) code = code.replace(",\n", "\n");
        out.append("\n///|\n").append(code).append('\n');
    }
    private void write(Grammar g, String file, String text) {
        try (Writer writer = gen.tool.getOutputFileWriter(g, file)) { writer.write(text); }
        catch (IOException e) { throw new IllegalStateException("Cannot write " + file, e); }
    }

    @Override protected void genFile(Grammar g, ST ignored, String file) {
        if (file.endsWith(".tokens")) { super.genFile(g, ignored, file); return; }
        StringBuilder out = new StringBuilder("// Generated by MoonBitTarget; ANTLR 4.13.2.\n");
        if (file.endsWith("Listener.mbt")) emitListener(g, out);
        else if (file.endsWith("Visitor.mbt")) emitVisitor(g, out);
        else emitRecognizer(g, out);
        write(g, file, out.toString().replaceAll("self\\.(terminal|enter_[A-Za-z_0-9]+|exit_[A-Za-z_0-9]+|visit_[A-Za-z_0-9]+)\\(", "(self.$1)("));
        write(g, "moon.pkg", "import { \"wdgodghl/moonantlr\" @runtime }\n");
    }

    private void emitRecognizer(Grammar g, StringBuilder out) {
        String data = Arrays.toString(ATNSerializer.getSerialized(g.atn).toArray());
        String recognizer = g.getRecognizerName();
        if (g.isLexer()) {
            block(out, "pub fn lexer_data() -> Array[Int] { " + data + " }");
            block(out, "pub struct " + recognizer + " { atn : @runtime.Atn }");
            block(out, "pub fn " + recognizer + "::new() -> " + recognizer + " raise @runtime.RuntimeError { { atn: @runtime.deserialize(lexer_data()) } }");
            block(out, "pub fn " + recognizer + "::tokenize(self : " + recognizer + ", source : String) -> Array[@runtime.Token] raise @runtime.RuntimeError { self.atn.tokenize(source) }");
            return;
        }
        block(out, "pub fn parser_data() -> Array[Int] { " + data + " }");
        List<String> rules = new ArrayList<>();
        for (String name : g.getRuleNames()) rules.add(q(name));
        List<String> vocab = new ArrayList<>();
        for (int i = 0; i <= g.getMaxTokenType(); i++) vocab.add(q(g.getVocabulary().getDisplayName(i)));
        block(out, "pub fn grammar() -> @runtime.Grammar raise @runtime.RuntimeError { { lexer: @runtime.deserialize(lexer_data()), parser: @runtime.deserialize(parser_data()), rules: " + rules + ", vocabulary: " + vocab + " } }");
        block(out, "pub struct " + recognizer + " { grammar : @runtime.Grammar }");
        block(out, "pub fn " + recognizer + "::new() -> " + recognizer + " raise @runtime.RuntimeError { {grammar: grammar()} }");
        for (Rule rule : g.rules.values()) {
            String ctx = type(g, rule.name);
            block(out, "pub struct " + ctx + " { node : @runtime.RuleContext }");
            block(out, "pub fn " + ctx + "::raw(self : " + ctx + ") -> @runtime.RuleContext { self.node }");
            block(out, "pub fn " + recognizer + "::parse_" + rule.name + "(self : " + recognizer + ", source : String) -> " + ctx + " raise @runtime.RuntimeError { {node: self.grammar.parse_context(source, start_rule=" + rule.index + ")} }");
            Set<String> refs = new TreeSet<>();
            for (GrammarAST ref : rule.ast.getNodesWithType(ANTLRParser.RULE_REF))
                if (g.getRule(ref.getText()) != null) refs.add(ref.getText());
            if (rule instanceof LeftRecursiveRule) refs.add(rule.name);
            for (String ref : refs) {
                block(out, "pub fn " + ctx + "::" + method(ref) + "(self : " + ctx + ") -> Array[" + type(g, ref) + "] { self.node.rules(" + q(ref) + ").map(node => " + type(g, ref) + "::{node}) }");
            }
            for (String token : new TreeSet<>(rule.getTokenRefs())) {
                String tokenName = token.startsWith("'") ? "literal_" + g.getTokenType(token) : token;
                block(out, "pub fn " + ctx + "::get_token_" + tokenName + "(self : " + ctx + ") -> Array[@runtime.Token] { self.node.tokens(" + g.getTokenType(token) + ") }");
            }
            emitLabels(g, rule, ctx, out);
        }
    }

    private void emitLabels(Grammar g, Rule rule, String ctx, StringBuilder out) {
        for (Map.Entry<String, List<LabelElementPair>> entry : rule.getElementLabelDefs().entrySet()) {
            LabelElementPair first = entry.getValue().get(0);
            Set<Integer> states = new TreeSet<>();
            for (LabelElementPair pair : entry.getValue()) collectStates(pair.element, states);
            if (rule instanceof LeftRecursiveRule) {
                LeftRecursiveRule left = (LeftRecursiveRule)rule;
                for (org.antlr.v4.runtime.misc.Pair<GrammarAST,String> pair : left.leftRecursiveRuleRefLabels)
                    if (pair.a.getText().equals(entry.getKey())) states.add(-1);
            }
            if (states.isEmpty()) continue;
            if (first.type == LabelType.RULE_LABEL || first.type == LabelType.RULE_LIST_LABEL) {
                String child = first.element.getText();
                if (g.getRule(child) == null) continue;
                block(out, "pub fn " + ctx + "::label_" + entry.getKey() + "(self : " + ctx + ") -> Array[" + type(g, child) + "] { self.node.rules(" + q(child) + ", states=" + states + ").map(node => " + type(g, child) + "::{node}) }");
            } else {
                block(out, "pub fn " + ctx + "::label_" + entry.getKey() + "(self : " + ctx + ") -> Array[@runtime.Token] { self.node.select_tokens(" + states + ") }");
            }
        }
        Map<String,List<org.antlr.v4.runtime.misc.Pair<Integer,AltAST>>> labels = rule.getAltLabels();
        StringBuilder alternatives = new StringBuilder();
        if (labels != null) for (String label : new TreeSet<>(labels.keySet())) {
            Set<Integer> states = new TreeSet<>();
            for (org.antlr.v4.runtime.misc.Pair<Integer,AltAST> alt : labels.get(label)) {
                // Entry into an alternative is distinguished by its own ATN states,
                // never by token text or a fixed child position.
                collectStates(alt.b, states);
            }
            if (rule instanceof LeftRecursiveRule) {
                LeftRecursiveRule left = (LeftRecursiveRule)rule;
                List<org.antlr.v4.analysis.LeftRecursiveRuleAltInfo> alts = new ArrayList<>(left.recPrimaryAlts);
                alts.addAll(left.recOpAlts.values());
                for (org.antlr.v4.analysis.LeftRecursiveRuleAltInfo alt : alts)
                    if (label.equals(alt.altLabel)) collectStates(alt.altAST, states);
            }
            String altType = type(g, label);
            block(out, "pub struct " + altType + " { node : @runtime.RuleContext }");
            block(out, "pub fn " + altType + "::raw(self : " + altType + ") -> @runtime.RuleContext { self.node }");
            block(out, "pub fn " + altType + "::as_rule(self : " + altType + ") -> " + ctx + " { {node: self.node} }");
            alternatives.append("if self.node.path.any(state => ").append(states).append(".contains(state)) { return Some(").append(q(label)).append(") }\n");
            block(out, "pub fn " + ctx + "::as_" + label + "(self : " + ctx + ") -> " + altType + "? { if self.alternative() == Some(" + q(label) + ") { Some({node: self.node}) } else { None } }");
        }
        block(out, "pub fn " + ctx + "::alternative(self : " + ctx + ") -> String? { " + alternatives + (alternatives.length()==0 ? "ignore(self)\n" : "") + "None }");
    }

    private static void collectStates(GrammarAST node, Set<Integer> states) {
        if (node.atnState != null) states.add(node.atnState.stateNumber);
        for (int i = 0; i < node.getChildCount(); i++) collectStates((GrammarAST)node.getChild(i), states);
    }

    private void emitVisitor(Grammar g, StringBuilder out) {
        String name = g.name + "Visitor";
        StringBuilder fields = new StringBuilder("terminal : (@runtime.Token) -> T,\n");
        StringBuilder init = new StringBuilder("terminal,\n");
        StringBuilder cases = new StringBuilder();
        for (Rule rule : g.rules.values()) {
            String ctx = type(g, rule.name);
            fields.append("visit_").append(rule.name).append(" : (").append(ctx).append(", Array[T]) -> T,\n");
            init.append("visit_").append(rule.name).append(": (context, children) => rule(context.raw(), children),\n");
            cases.append(q(rule.name)).append(" => { let context = ").append(ctx).append("::{node};\n");
            Map<String,List<org.antlr.v4.runtime.misc.Pair<Integer,AltAST>>> labels = rule.getAltLabels();
            if (labels != null) for (String label : new TreeSet<>(labels.keySet())) {
                fields.append("visit_alt_").append(label).append(" : ((").append(type(g,label)).append(", Array[T]) -> T)?,\n");
                init.append("visit_alt_").append(label).append(": None,\n");
                cases.append("if context.alternative() == Some(").append(q(label)).append(") { if self.visit_alt_").append(label).append(" is Some(callback) { return callback(").append(type(g,label)).append("::{node}, values) } }\n");
            }
            cases.append("self.visit_").append(rule.name).append("(context, values) }\n");
        }
        block(out, "pub(all) struct " + name + "[T] { " + fields + " }");
        block(out, "pub fn[T] " + name + "::new(terminal~ : (@runtime.Token) -> T, rule~ : (@runtime.RuleContext, Array[T]) -> T) -> " + name + "[T] { {" + init + "} }");
        block(out, "pub fn[T] " + name + "::visit(self : " + name + "[T], node : @runtime.RuleContext) -> T { let values = node.children.map(child => match child { @runtime.TokenChild(token) => self.terminal(token); @runtime.RuleChild(context) => self.visit(context) }); match node.name { " + cases + "_ => abort(\"foreign rule context\") } }");
    }

    private void emitListener(Grammar g, StringBuilder out) {
        String name = g.name + "Listener";
        StringBuilder fields = new StringBuilder("terminal : (@runtime.Token) -> Unit,\n");
        StringBuilder init = new StringBuilder("terminal: (_) => (),\n");
        StringBuilder enter = new StringBuilder(), exit = new StringBuilder();
        for (Rule rule : g.rules.values()) {
            String ctx = type(g, rule.name);
            for (String phase : new String[]{"enter", "exit"}) {
                fields.append(phase).append('_').append(rule.name).append(" : (").append(ctx).append(") -> Unit,\n");
                init.append(phase).append('_').append(rule.name).append(": (_) => (),\n");
                (phase.equals("enter") ? enter : exit).append(q(rule.name)).append(" => self.").append(phase).append('_').append(rule.name).append('(').append(ctx).append("::{node})\n");
            }
        }
        StringBuilder altEnter = new StringBuilder(), altExit = new StringBuilder();
        for (Rule rule : g.rules.values()) {
            Map<String,List<org.antlr.v4.runtime.misc.Pair<Integer,AltAST>>> labels = rule.getAltLabels();
            if (labels == null) continue;
            for (String label : new TreeSet<>(labels.keySet())) for (String phase : new String[]{"enter", "exit"}) {
                fields.append(phase).append("_alt_").append(label).append(" : (").append(type(g,label)).append(") -> Unit,\n");
                init.append(phase).append("_alt_").append(label).append(": (_) => (),\n");
                (phase.equals("enter") ? altEnter : altExit).append("if node.name == ").append(q(rule.name)).append(" { if ").append(type(g,rule.name)).append("::{node}.alternative() == Some(").append(q(label)).append(") { self.").append(phase).append("_alt_").append(label).append('(').append(type(g,label)).append("::{node}) } }\n");
            }
        }
        block(out, "pub(all) struct " + name + " { " + fields + " }");
        block(out, "pub fn " + name + "::new() -> " + name + " { {" + init + "} }");
        block(out, "pub fn " + name + "::walk(self : " + name + ", node : @runtime.RuleContext) -> Unit { match node.name { " + enter + "_ => () }; " + altEnter + "for child in node.children { match child { @runtime.TokenChild(token) => self.terminal(token); @runtime.RuleChild(context) => self.walk(context) } }; " + altExit + "match node.name { " + exit + "_ => () } }");
    }
}
