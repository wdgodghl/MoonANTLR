"""Generate a MoonBit grammar module from ANTLR 4.13.2 .interp output.

The upstream Java tool does grammar analysis. MoonANTLR executes the resulting
ATNs in MoonBit; it does not translate Java parser source or execute Java at run time.
"""

import argparse
import ast
import hashlib
import json
import os
from pathlib import Path
import subprocess
import tempfile

ANTLR_VERSION = "4.13.2"
ANTLR_SHA256 = "eae2dfa119a64327444672aff63e9ec35a20180dc5b8090b7a6ab85125df4d76"


def read_sections(path):
    sections = {}
    current = None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.endswith(":"):
            current = line[:-1]
            sections[current] = []
        elif line and current:
            sections[current].append(line)
    return sections


def read_interp(path):
    sections = read_sections(path)
    if "atn" not in sections or "rule names" not in sections:
        raise ValueError("Missing ATN or rule names in .interp artifact")
    atn = ast.literal_eval("".join(sections["atn"]))
    if not isinstance(atn, list) or any(type(n) is not int for n in atn):
        raise ValueError("Expected an integer serialized ATN")
    if not atn or atn[0] != 4:
        raise ValueError("Expected ANTLR serialized ATN version 4")
    return atn, sections["rule names"]


def read_vocabulary(path):
    sections = read_sections(path)
    literals = sections.get("token literal names", [])
    symbolic = sections.get("token symbolic names", [])
    names = []
    for index in range(max(len(literals), len(symbolic))):
        literal = literals[index] if index < len(literals) else "null"
        symbol = symbolic[index] if index < len(symbolic) else "null"
        names.append(literal if literal != "null" else symbol if symbol != "null" else str(index))
    return names


def render(grammar_path, lexer, parser, rules, vocabulary, lexer_path=None):
    digest = hashlib.sha256(grammar_path.read_bytes()).hexdigest()
    extra = ""
    if lexer_path:
        extra = f"// Lexer: {lexer_path.name}; SHA256: {hashlib.sha256(lexer_path.read_bytes()).hexdigest()}\n"
    return (
        f"// Generated by tools/generate.py; ANTLR {ANTLR_VERSION}.\n"
        f"// Source: {grammar_path.name}; SHA256: {digest}\n" + extra + "\n"
        f"///|\npub fn lexer_data() -> Array[Int] {{ {json.dumps(lexer)} }}\n\n"
        f"///|\npub fn parser_data() -> Array[Int] {{ {json.dumps(parser)} }}\n\n"
        "///|\npub fn grammar() -> @runtime.Grammar raise @runtime.RuntimeError {\n"
        "  let lexer = @runtime.deserialize(lexer_data())\n"
        "  let parser = @runtime.deserialize(parser_data())\n"
        f"  {{ lexer, parser, rules: {json.dumps(rules)}, vocabulary: {json.dumps(vocabulary)} }}\n"
        "}\n"
    )


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("grammar", type=Path)
    cli.add_argument("--output", required=True, type=Path)
    cli.add_argument("--lexer", type=Path, help="Lexer grammar for a separate parser grammar")
    cli.add_argument("--jar", type=Path, default=os.environ.get("ANTLR_JAR"))
    cli.add_argument("--java", default=os.environ.get("JAVA", "java"))
    args = cli.parse_args()
    if not args.jar or not args.jar.is_file():
        cli.error("Set --jar or ANTLR_JAR to the official ANTLR 4.13.2 complete jar")
    if hashlib.sha256(args.jar.read_bytes()).hexdigest() != ANTLR_SHA256:
        cli.error("ANTLR jar checksum mismatch: expected the official 4.13.2 artifact")
    grammar = args.grammar.resolve()
    if not grammar.is_file():
        cli.error("Grammar file not found")
    lexer_path = args.lexer.resolve() if args.lexer else None
    if lexer_path and not lexer_path.is_file():
        cli.error("Lexer grammar file not found")
    scratch = Path(__file__).resolve().parents[1] / ".local"
    scratch.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="generate-", dir=scratch) as directory:
        subprocess.run(
            [args.java, "-Dfile.encoding=UTF-8", "-jar", str(args.jar.resolve()), "-encoding", "UTF-8", "-Dlanguage=Java",
             "-Xexact-output-dir", "-lib", directory, "-o", directory]
            + ([str(lexer_path)] if lexer_path else []) + [str(grammar)], check=True,
        )
        lexer_name = lexer_path.stem if lexer_path else grammar.stem + "Lexer"
        lexer, _ = read_interp(Path(directory) / (lexer_name + ".interp"))
        parser, rules = read_interp(Path(directory) / (grammar.stem + ".interp"))
        vocabulary = read_vocabulary(Path(directory) / (grammar.stem + ".interp"))
        source = render(grammar, lexer, parser, rules, vocabulary, lexer_path)
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "grammar.mbt").write_text(source, encoding="utf-8", newline="\n")
    (args.output / "moon.pkg").write_text(
        'import { "wdgodghl/moonantlr" @runtime }\n', encoding="utf-8", newline="\n",
    )
    print(f"Generated {grammar.stem}: {len(rules)} parser rules")


if __name__ == "__main__":
    main()
