"""Generate conformance cases from the real ANTLR 4.13.2 Java target.

Generated expected results are committed so ordinary MoonBit tests need no Java.
Run this tool after grammar/runtime changes, then run moon fmt and moon test.
"""

import argparse
import base64
import hashlib
import json
import os
from pathlib import Path
import random
import subprocess
import tempfile
from generate import ANTLR_SHA256

ROOT = Path(__file__).resolve().parents[1]


def value(rng, depth=0):
    kind = rng.randrange(4 if depth >= 3 else 6)
    if kind == 0:
        return None
    if kind == 1:
        return rng.choice([True, False])
    if kind == 2:
        return rng.randint(-10000, 10000) / rng.choice([1, 10, 100])
    if kind == 3:
        return rng.choice(["", "MoonANTLR", "中文😀", "quote\"slash\\", "line\n\ttab"])
    if kind == 4:
        return [value(rng, depth + 1) for _ in range(rng.randrange(5))]
    return {"key" + str(i): value(rng, depth + 1) for i in range(rng.randrange(4))}


def expression(rng, depth=0):
    if depth >= 3 or rng.random() < 0.35:
        return str(rng.randrange(100))
    return "(" + expression(rng, depth + 1) + rng.choice(["+", "-", "*", "/"]) + expression(rng, depth + 1) + ")"


def corpus():
    rng = random.Random(20261105)
    json_cases = ["{}", "[]", "true", "false", "null", "-0", "1e+10", '"😀中"', '"\\uD83D\\uDE00"', "[1,2,3]", "\r\n {\"x\": -1.2E-3} \t"]
    json_cases += [json.dumps(value(rng), ensure_ascii=False, indent=rng.choice([None, 2])) for _ in range(70)]
    json_cases += ["", "[", "{", "[1,]", "{\"x\":}", "01", "true false", '"bad\\x"', '"raw\nnewline"', "1.", "1e", "+1", "{x:1}", "[1 2]", "null!", "True", "--1"]
    arithmetic = ["1+2*3", "(1+2)*3", " 12 / 3 - 2\n", "1-2-3", "1/(2+3)"]
    arithmetic += [expression(rng) for _ in range(50)]
    arithmetic += ["", "1+", "+1", "1+*2", "(1+2", "1 2", "1.2", "a", "1)2", "()"]
    return {"Json": json_cases, "Arithmetic": arithmetic}


def run(args, **kwargs):
    return subprocess.run(args, check=True, encoding="utf-8", **kwargs)


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--jar", required=True, type=Path)
    cli.add_argument("--java", default=os.environ.get("JAVA", "java"))
    cli.add_argument("--javac", default=os.environ.get("JAVAC", "javac"))
    args = cli.parse_args()
    jar = args.jar.resolve()
    if hashlib.sha256(jar.read_bytes()).hexdigest() != ANTLR_SHA256:
        cli.error("ANTLR jar checksum mismatch")
    scratch = ROOT / ".local"
    scratch.mkdir(exist_ok=True)
    output = ["// Generated by tools/oracle.py from ANTLR 4.13.2 Java output.", "// Seed: 20261105. No Java is needed to run these tests.", ""]
    counts = {}
    with tempfile.TemporaryDirectory(prefix="oracle-", dir=scratch) as temp:
        directory = Path(temp)
        run([args.java, "-Dfile.encoding=UTF-8", "-jar", str(jar), "-encoding", "UTF-8", "-Dlanguage=Java", "-Xexact-output-dir", "-o", str(directory)] + [str(ROOT / "grammars" / (name + ".g4")) for name in corpus()])
        run([args.javac, "-encoding", "UTF-8", "-cp", str(jar), "-d", str(directory), str(ROOT / "tools" / "Oracle.java")] + [str(p) for p in directory.glob("*.java")])
        for name, cases in corpus().items():
            payload = "".join(base64.b64encode(s.encode()).decode() + "\n" for s in cases)
            result = run([args.java, "-Dfile.encoding=UTF-8", "-cp", str(directory) + os.pathsep + str(jar), "Oracle", name], input=payload, capture_output=True)
            expected = [json.loads(line) for line in result.stdout.splitlines()]
            if len(expected) != len(cases):
                raise RuntimeError("Oracle output count differs from input count")
            counts[name] = {"cases": len(cases), "accepted": sum(row["accepted"] for row in expected)}
            alias = "json" if name == "Json" else "arithmetic"
            for index, (source, row) in enumerate(zip(cases, expected)):
                quoted = json.dumps(source, ensure_ascii=False)
                output += ["///|", f'test "Java oracle {name} {index:03d}" {{', f"  let grammar = @{alias}.grammar()"]
                if row["accepted"]:
                    output += [f"  let source = {quoted}", f"  assert_eq(grammar.parse(source).to_sexpr(), {json.dumps(row['tree'], ensure_ascii=False)})", "  let actual = grammar.tokenize(source).map(t => (t.kind, t.text, t.start, t.end, t.line, t.column, t.channel))"]
                    tuples = ", ".join("(" + ", ".join(json.dumps(v, ensure_ascii=False) for v in token) + ")" for token in row["tokens"])
                    output += [f"  @debug.assert_eq(actual, [{tuples}])"]
                else:
                    output += [f"  let rejected = try {{ let _ = grammar.parse({quoted}); false }} catch {{ _ => true }}", "  assert_true(rejected)"]
                output += ["}", ""]
    (ROOT / "tests" / "oracle_test.mbt").write_text("\n".join(output), encoding="utf-8", newline="\n")
    (ROOT / "tests" / "oracle-manifest.json").write_text(json.dumps({"upstream": "ANTLR 4.13.2 Java target", "seed": 20261105, "grammars": counts}, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps(counts))


if __name__ == "__main__":
    main()
