"""Compare exceptional rule unwinding with the real ANTLR 4.13.2 Java target."""
import argparse,hashlib,json,os,subprocess
from pathlib import Path
from generate import ANTLR_SHA256
ROOT=Path(__file__).resolve().parents[1]

def main():
    cli=argparse.ArgumentParser(description=__doc__)
    cli.add_argument('--jar',type=Path,required=True)
    cli.add_argument('--java',default=os.environ.get('JAVA','java'))
    cli.add_argument('--javac',default=os.environ.get('JAVAC','javac'))
    args=cli.parse_args();jar=args.jar.resolve()
    if hashlib.sha256(jar.read_bytes()).hexdigest()!=ANTLR_SHA256:cli.error('ANTLR jar checksum mismatch')
    directory=ROOT/'.local/lifecycle-reference';directory.mkdir(parents=True,exist_ok=True)
    subprocess.run([args.java,'-jar',str(jar),'-encoding','UTF-8','-Xexact-output-dir','-o',str(directory),str(ROOT/'grammars/Lifecycle.g4'),str(ROOT/'grammars/Exceptions.g4')],check=True)
    subprocess.run([args.javac,'-encoding','UTF-8','-cp',str(jar),'-d',str(directory),str(ROOT/'tools/UpstreamAttributes.java'),str(ROOT/'tools/Oracle.java'),str(ROOT/'tools/PredictionTrace.java'),str(ROOT/'tools/LifecycleExceptionOracle.java')]+list(map(str,directory.glob('*.java'))),check=True)
    output=['// Generated by tools/lifecycle_oracle.py using ANTLR 4.13.2 Java.','']
    cases=[]
    for rule,stages in [('document',['','init','inline','after','finally','inline,finally']),('nested',['','init','inline','after','finally','outer-init','outer-after','outer-finally','inline,finally','inline,outer-finally'])]:
        cases += [('Lifecycle',rule,stage,'x',0 if rule=='document' else 4) for stage in stages]
    cases += [('Exceptions','caught',stage,source,0) for source,stage in [('x',''),('x','catch'),('x','catch,finally'),('a',''),('ab','inline')]]
    cases += [('Exceptions','caught_host',stage,'x',1) for stage in ['','inline','inline,catch','inline,finally']]
    cases += [('Exceptions','specific','','x',2),('Exceptions','specific','','xaa',2),('Exceptions','predicate_failure','','x',3)]
    cases += [("Exceptions","outer",stage,"x",4) for stage in ["","inline"]]
    cases += [("Lifecycle","argument_caller",stage,"x",5) for stage in ["","argument","after","argument,finally"]]
    for grammar,rule,stage,source,start in cases:
        result=subprocess.run([args.java,'-cp',str(directory)+os.pathsep+str(jar),'LifecycleExceptionOracle',grammar,rule,stage,source],capture_output=True,encoding='utf8',check=True)
        row=json.loads(result.stdout)
        output+=['///|',f'test "Java lifecycle exception {grammar} {rule} {stage or "success"} {source}" {{',
            f'  let actual = lifecycle_exception({start}, {json.dumps(stage.split(",") if stage else [])}, caught={str(grammar=="Exceptions").lower()}, input={json.dumps(source)})',
            f'  let expected : (Array[String], String, Int32, String, Array[Int32], Array[Int32], Int32) = ({json.dumps(row["events"])}, {json.dumps(row["error"])}, {row["diagnostics"]}, {json.dumps(row["tree"])}, {json.dumps(row["totals"])}, {json.dumps(row["finalCounts"])}, {row["captures"]})',
            '  @debug.assert_eq(actual, expected)','}','']
    (ROOT/'tests/lifecycle_exception_test.mbt').write_text('\n'.join(output),encoding='utf8',newline='\n')
    print('Java exceptional lifecycle comparisons:',len(cases))
if __name__=='__main__':main()
