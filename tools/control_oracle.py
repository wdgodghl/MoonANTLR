"""Verify live parser controls and invocation Token boundaries with Java."""
import argparse,hashlib,json,os,subprocess
from pathlib import Path
from generate import ANTLR_SHA256
ROOT=Path(__file__).resolve().parents[1]

def main():
    cli=argparse.ArgumentParser(description=__doc__)
    cli.add_argument('--jar',type=Path,required=True)
    args=cli.parse_args();jar=args.jar.resolve()
    if hashlib.sha256(jar.read_bytes()).hexdigest()!=ANTLR_SHA256:cli.error('ANTLR jar checksum mismatch')
    java=os.environ.get('JAVA','java');javac=os.environ.get('JAVAC','javac')
    directory=ROOT/'.local/control-reference';directory.mkdir(parents=True,exist_ok=True)
    subprocess.run([java,'-jar',str(jar),'-encoding','UTF-8','-Xexact-output-dir','-o',str(directory),str(ROOT/'grammars/Control.g4')],check=True)
    subprocess.run([javac,'-encoding','UTF-8','-cp',str(jar),'-d',str(directory)]+list(map(str,directory.glob('*.java')))+[str(ROOT/'tools'/name) for name in ['ControlOracle.java','UpstreamAttributes.java','Oracle.java','PredictionTrace.java']],check=True)
    output=['// Generated by tools/control_oracle.py from ANTLR 4.13.2 Java.','']
    cases=[(0,'document',source) for source in ['ab','a b','a','b','aab','ac']]+[(1,'branch',source) for source in ['ab','ac','aa','a','ba']]+[(2,'toggle','aa'),(2,'toggle','a a'),(4,'boundaries','a b')]
    for start,rule,source in cases:
        row=json.loads(subprocess.check_output([java,'-cp',str(directory)+os.pathsep+str(jar),'ControlOracle',rule,source],encoding='utf8'))
        output+=['///|',f'test "Java runtime control {rule} {source}" {{', f'  let actual = control_observation({start}, {json.dumps(source)})']
        expected='error:'+row['error']+':'+str(row['line'])+':'+str(row['column']) if row['error'] else row['tree']+'\n'+row['boundaries']
        output += [f'  assert_eq(actual, {json.dumps(expected)})','}','']
    (ROOT/'tests/control_oracle_test.mbt').write_text('\n'.join(output),encoding='utf8',newline='\n')
    print('Independent Java runtime control comparisons:',len(cases))
if __name__=='__main__':main()
